    // damit ein späterer Sprachwechsel (und jeder Reload) die gespeicherte Wahl nutzt.
    var q = (location.search.match(/[?&]region=(us|eu)(?=&|#|$)/i) || [])[1];
    if(q){
      var ql = q.toLowerCase() === 'us' ? 'en' : 'de';
      store('lusides_lang', ql);
      try{
        var u = new URL(location.href);
        u.searchParams.delete('region');
        history.replaceState(history.state, '', u.pathname + u.search + u.hash);
      }catch(e){}
      return ql;
    }
